void ShaderGenerator::EmitVertexInputs(std::ostringstream& os) const
{
	auto inputs = BuildVertexInputs(m_MaterialDomain, m_RequiredAttributes);
	for (auto& v : inputs)
		os << "layout(location = " << (int)v.location << ") in vec4 " << v.name << ";\n";
	os << '\n';
}

void ShaderGenerator::EmitVaryingOut(std::ostringstream& os) const
{
	auto content = LoadTemplate("surface_varying.glsl");
	os << "#define VARYING out\n" << content << '\n';
}

void ShaderGenerator::EmitVaryingIn(std::ostringstream& os) const
{
	auto content = LoadTemplate("surface_varying.glsl");
	os << "#define VARYING in\n" << content << '\n';
}

void ShaderGenerator::EmitFragmentOutputs(std::ostringstream& os) const
{
	if (m_Outputs.empty())
		return;

	os << "// Fragment outputs\n";
	int colorIndex = 0;
	for (const auto& o : m_Outputs)
	{
		if (o.target != MaterialBuilder::OutputTarget::COLOR)
			continue;

		const char* glslType = "vec4";
		const char* fieldTypeStr = "float4";
		switch (o.type)
		{
		case MaterialBuilder::OutputType::FLOAT:  glslType = "float"; fieldTypeStr = "float";  break;
		case MaterialBuilder::OutputType::FLOAT2: glslType = "vec2";  fieldTypeStr = "float2"; break;
		case MaterialBuilder::OutputType::FLOAT3: glslType = "vec3";  fieldTypeStr = "float3"; break;
		case MaterialBuilder::OutputType::FLOAT4: glslType = "vec4";  fieldTypeStr = "float4"; break;
		}

		int idx = colorIndex++;
		os << "layout(location = " << idx << ") out " << glslType << " " << o.name << ";\n";
		os << "#define FRAG_OUTPUT" << idx << " " << o.name << "\n";
		os << "#define FRAG_OUTPUT_AT" << idx << "\n";
		os << "#define FRAG_OUTPUT_MATERIAL_TYPE" << idx << " " << glslType << "\n";
		os << "#define FRAG_OUTPUT_SWIZZLE" << idx << " " << o.name << "\n";
		os << "#define FRAG_OUTPUT_PRECISION" << idx << "\n";
	}
	os << '\n';
}

std::string ShaderGenerator::MainTemplate(Stage stage, MaterialPass pass) const
{
	if (stage == Stage::Vertex)
	{
		switch (pass)
		{
		case MaterialPass::Depth:    return "surface_depth_main.vs";
		case MaterialPass::Surface:  return (m_Pipeline == Pipeline::FORWARD)
		                            ? "surface_forward_main.vs"
		                            : "surface_deferred_main.vs";
		case MaterialPass::Lighting: return "surface_shading_main.vs";
		}
	}
	else
	{
		switch (pass)
		{
		case MaterialPass::Depth:    return "surface_depth_main.fs";
		case MaterialPass::Surface:  return (m_Pipeline == Pipeline::FORWARD)
		                            ? "surface_forward_main.fs"
		                            : "surface_deferred_main.fs";
		case MaterialPass::Lighting: return "surface_shading_main.fs";
		}
	}
	return {};
}

// =============================================================================
// Constructor
// =============================================================================

ShaderGenerator::ShaderGenerator(
	std::string const& materialName,
	Pipeline pipeline, Shading shadingModel, MaterialDomain domain,
	BufferInterfaceBlock const& materialUib, SamplerInterfaceBlock const& materialSib,
	RHI::AttributeBitset const& requiredAttributes,
	MaterialBuilder::PropertyList const& properties,
	MaterialBuilder::VariableList const& variables,
	MaterialBuilder::OutputList const& outputs,
	MaterialBuilder::PreprocessorDefineList const& defines,
	MaterialBuilder::PushConstantList const& pushConstants,
	std::string const& fragmentCode, size_t fragmentLineOffset,
	std::string const& vertexCode, size_t vertexLineOffset)
	: m_MaterialName(materialName)
	, m_Properties()
	, m_Pipeline(pipeline)
	, m_ShadingModel(shadingModel)
	, m_MaterialDomain(domain)
	, m_MaterialUib(&materialUib)
	, m_MaterialSib(&materialSib)
	, m_RequiredAttributes(requiredAttributes)
	, m_Defines(defines)
	, m_PushConstants(pushConstants)
{
	std::copy(std::begin(properties), std::end(properties), std::begin(m_Properties));

	std::copy(std::begin(variables), std::end(variables), std::begin(m_Variables));
	std::copy(std::begin(outputs), std::end(outputs), std::back_inserter(m_Outputs));

	m_MaterialFragmentCode = fragmentCode;
	m_MaterialVertexCode = vertexCode;
	m_IsMaterialVertexShaderEmpty = vertexCode.empty();

	if (m_MaterialFragmentCode.empty())
	{
		if (m_MaterialDomain == MaterialDomain::SURFACE)
			m_MaterialFragmentCode = "void material(inout MaterialInputs m) {\n    prepareMaterial(m);\n}\n";
		else if (m_MaterialDomain == MaterialDomain::POST_PROCESS)
			m_MaterialFragmentCode = "void postProcess(inout PostProcessInputs p) {\n}\n";
		else if (m_MaterialDomain == MaterialDomain::COMPUTE)
			m_MaterialFragmentCode = "void compute() {\n}\n";
	}

	if (m_MaterialVertexCode.empty())
	{
		if (m_MaterialDomain == MaterialDomain::SURFACE)
			m_MaterialVertexCode = "void materialVertex(inout MaterialVertexInputs m) {\n}\n";
		else if (m_MaterialDomain == MaterialDomain::POST_PROCESS)
			m_MaterialVertexCode = "void postProcessVertex(inout PostProcessVertexInputs m) {\n}\n";
	}
}

// =============================================================================
// Surface-domain dispatch
// =============================================================================

std::string ShaderGenerator::GenerateShader(Stage stage, MaterialPass pass,
                                            const std::string& userCode) const
{
	switch (stage)
	{
	case Stage::Vertex:
		switch (pass)
		{
		case MaterialPass::Depth:    return GenDepthVS(userCode);
		case MaterialPass::Surface:  return GenSurfaceVS(userCode);
		case MaterialPass::Lighting: return GenLightingVS(userCode);
		}
		break;

	case Stage::Fragment:
		switch (pass)
		{
		case MaterialPass::Depth:    return GenDepthFS(userCode);
		case MaterialPass::Surface:  return GenSurfaceFS(userCode);
		case MaterialPass::Lighting: return GenLightingFS(userCode);
		}
		break;

	case Stage::Compute:
		return GenerateComputeShader(userCode);
	}
	return {};
}

std::string ShaderGenerator::GeneratePostProcessShader(Stage stage,
                                                       const std::string& userCode) const
{
	switch (stage)
	{
	case Stage::Vertex:   return GenPostProcessVS(userCode);
	case Stage::Fragment: return GenPostProcessFS(userCode);
	default: return {};
	}
}

// =============================================================================
// Depth — Vertex
// =============================================================================

std::string ShaderGenerator::GenDepthVS(const std::string& code) const
{
	std::ostringstream os;
	CodeGenerator cg;

	EmitHeader(os, cg);
	os << '\n';

	if (m_TargetVulkan)
		os << "#define TARGET_VULKAN_ENVIRONMENT\n";
	os << "#define VERTEX_STAGE\n\n";

	os << LoadTemplate("common_defines.glsl") << '\n';
	os << LoadTemplate("common_math.glsl") << '\n';

	EmitVertexInputs(os);
	EmitVaryingOut(os);

	for (auto& file : Provider::GetDepthVertex())
		os << LoadTemplate(file) << '\n';

	os << LoadTemplate("common_getter.glsl") << '\n';
	cg.generateVaryingDeclarations(os, m_Variables, "out");

	if (!code.empty())
		os << "// User vertex code\n" << code << '\n';

	os << LoadTemplate(MainTemplate(Stage::Vertex, MaterialPass::Depth)) << '\n';
	return os.str();
}

