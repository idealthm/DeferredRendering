static const char* ToString(MaterialDomain domain)
{
	switch (domain)
	{
	case MaterialDomain::SURFACE:      return "surface";
	case MaterialDomain::POST_PROCESS: return "postprocess";
	case MaterialDomain::COMPUTE:      return "compute";
	}
	return "unknown";
}

void ShaderGenerator::EmitHeader(std::ostringstream& os, CodeGenerator& cg,
                                 const MaterialSpec& spec) const
{
	os << "// Auto-generated by matc -- Material: " << spec.name << "\n";
	os << "// Domain: " << ToString(spec.domain) << "\n";
	os << "// Shading model: " << spec.shadingModel << "\n\n";
	os << "#version 460\n\n";
	os << LoadTemplate("surface_types.glsl") << '\n';

	cg.generateUniforms(os, UIB::GetPerViewUIB());
	cg.generateUniforms(os, UIB::GetPerRenderableUIB());

	if (!spec.materialUib.isEmpty())
		cg.generateUniforms(os, spec.materialUib);
	if (!spec.materialSib.isEmpty())
		cg.generateCommonSamplers(os, spec.materialSib);

	os << "// Feature macros for conditional compilation\n";
	cg.generateVaryingDefines(os, spec);
	cg.generateConstantDefines(os, spec);
	cg.generateAttributeDefines(os, spec);
	cg.generatePropertyDefines(os, spec);

	int shadingModelId = (spec.shadingModel == "lit") ? 1 : 0;
	os << "#define SHADING_MODEL_ID " << shadingModelId << "\n\n";
}

void ShaderGenerator::EmitLightHeader(std::ostringstream& os) const
{
	os << "// Auto-generated by matc\n\n";
	os << "#version 460\n\n";
	os << LoadTemplate("surface_types.glsl") << '\n';
}

// =============================================================================
// Shared emitters
