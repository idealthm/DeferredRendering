static const char* ToString(MaterialDomain domain)
{
	switch (domain)
	{
	case MaterialDomain::SURFACE:      return "surface";
	case MaterialDomain::POST_PROCESS: return "postprocess";
	case MaterialDomain::COMPUTE:      return "compute";
	}
	return "unknown";
}

void ShaderGenerator::EmitHeader(std::ostringstream& os, CodeGenerator& cg) const
{
	os << "// Auto-generated by matc -- Material: " << m_MaterialName << "\n";
	os << "// Domain: " << ToString(m_MaterialDomain) << "\n";
	os << "#version 460\n\n";
	os << LoadTemplate("surface_types.glsl") << '\n';

	cg.generateUniforms(os, UIB::GetPerViewUIB());
	cg.generateUniforms(os, UIB::GetPerRenderableUIB());

	if (m_MaterialUib && !m_MaterialUib->isEmpty())
		cg.generateUniforms(os, *m_MaterialUib);
	if (m_MaterialSib && !m_MaterialSib->isEmpty())
		cg.generateCommonSamplers(os, *m_MaterialSib);

	os << "// Feature macros for conditional compilation\n";
	cg.generateVaryingDefines(os, m_Variables);
	cg.generateConstantDefines(os, m_Defines);
	cg.generateAttributeDefines(os, m_RequiredAttributes);
	cg.generatePropertyDefines(os, m_Properties);

	int shadingModelId = m_ShadingModel == Shading::LIT;
	os << "#define SHADING_MODEL_ID " << shadingModelId << "\n\n";
}

void ShaderGenerator::EmitLightHeader(std::ostringstream& os) const
{
	os << "// Auto-generated by matc\n\n";
	os << "#version 460\n\n";
	os << LoadTemplate("surface_types.glsl") << '\n';
}

