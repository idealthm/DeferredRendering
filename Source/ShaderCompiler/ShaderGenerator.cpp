// =============================================================================
// Lighting — Fragment
// =============================================================================

std::string ShaderGenerator::GenLightingFS(const std::string& code) const
{
	std::ostringstream os;
	CodeGenerator cg;

	EmitHeader(os, cg);

	if (m_TargetVulkan)
		os << "#define TARGET_VULKAN_ENVIRONMENT\n";
	os << "#define LIGHTING_PASS\n";
	os << "#define FRAGMENT_STAGE\n\n";

	os << LoadTemplate("common_defines.glsl") << '\n';
	os << LoadTemplate("common_math.glsl") << '\n';
	os << LoadTemplate("common_shading.glsl") << '\n';
	os << LoadTemplate("surface_material_input.fs") << '\n';
	os << LoadTemplate("lighting_uniforms.glsl") << '\n';

	// IBL samplers — PER_VIEW descriptor set (ues )
	if (m_ShadingModel == Shading::LIT)
	{
		SamplerInterfaceBlock::SamplerInfoList iblSamplers = {
			{"irradianceMap", "irradianceMap", +PerViewBindingPoints::IBL_IRRADIANCE,
			 RHI::SamplerType::SAMPLER_CUBEMAP, RHI::SamplerFormat::FLOAT, false},
			{"prefilterMap", "prefilterMap", +PerViewBindingPoints::IBL_PREFILTER,
			 RHI::SamplerType::SAMPLER_CUBEMAP, RHI::SamplerFormat::FLOAT, false},
			{"brdfLut", "brdfLut", +PerViewBindingPoints::BRDF_LUT,
			 RHI::SamplerType::SAMPLER_2D, RHI::SamplerFormat::FLOAT, false},
		};
		cg.generateCommonSamplers(os, iblSamplers);
	}

	// GBuffer samplers — G_BUFFER descriptor set (auto bindings)
	{
		SamplerInterfaceBlock::SamplerInfoList gbufferSamplers = {
			{"gDepth", "gDepth", +GBufferBindingPoint::G_BUFFER_DEPTH,
			 RHI::SamplerType::SAMPLER_2D, RHI::SamplerFormat::FLOAT, false},
			{"gNormal", "gNormal", +GBufferBindingPoint::G_BUFFER_NORMAL,
			 RHI::SamplerType::SAMPLER_2D, RHI::SamplerFormat::FLOAT, false},
			{"gAlbedo", "gAlbedo", +GBufferBindingPoint::G_BUFFER_ALBEDO,
			 RHI::SamplerType::SAMPLER_2D, RHI::SamplerFormat::FLOAT, false},
			{"gMaterial", "gMaterial", +GBufferBindingPoint::G_BUFFER_MATERIAL,
			 RHI::SamplerType::SAMPLER_2D, RHI::SamplerFormat::FLOAT, false},
		};
		cg.generateCommonSamplers(os, gbufferSamplers);
	}

	os << LoadTemplate("surface_shading_parameters.fs") << '\n';

	if (!code.empty())
		os << "// User fragment code\n" << code << '\n';

	os << LoadTemplate("surface_shading_unlit.fs") << '\n';
	os << LoadTemplate("surface_shading_lit.fs") << '\n';
	os << LoadTemplate(MainTemplate(Stage::Fragment, MaterialPass::Lighting)) << '\n';
	return os.str();
}

// =============================================================================
// PostProcess — Vertex
// =============================================================================

std::string ShaderGenerator::GenPostProcessVS(const std::string& code) const
{
	std::ostringstream os;
	CodeGenerator cg;

	EmitLightHeader(os);

	if (m_TargetVulkan)
		os << "#define TARGET_VULKAN_ENVIRONMENT\n";
	os << "#define VERTEX_STAGE\n";
	os << "#define ATTRIBUTE in\n";
	os << "#define LOCATION_POSITION 0\n\n";

	os << LoadTemplate("common_defines.glsl") << '\n';

	cg.generateVaryingDefines(os, m_Variables);

	for (auto& file : Provider::GetPostProcessVertex())
		os << LoadTemplate(file) << '\n';

	if (!code.empty())
		os << "// User vertex code\n" << code << '\n';

	cg.generateVaryingDeclarations(os, m_Variables, "out");
	os << LoadTemplate("post_process_main.vs") << '\n';
	return os.str();
}

