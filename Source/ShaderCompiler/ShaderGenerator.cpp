void ShaderGenerator::EmitVertexInputs(std::ostringstream& os, const MaterialSpec& spec) const
{
	auto inputs = BuildVertexInputs(spec);
	for (auto& v : inputs)
		os << "layout(location = " << (int)v.location << ") in vec4 " << v.name << ";\n";
	os << '\n';
}

void ShaderGenerator::EmitVaryingOut(std::ostringstream& os) const
{
	auto content = LoadTemplate("surface_varying.glsl");
	os << "#define VARYING out\n" << content << '\n';
}

void ShaderGenerator::EmitVaryingIn(std::ostringstream& os) const
{
	auto content = LoadTemplate("surface_varying.glsl");
	os << "#define VARYING in\n" << content << '\n';
}

void ShaderGenerator::EmitFragmentOutputs(std::ostringstream& os, const MaterialSpec& spec) const
{
	if (spec.outputs.empty())
		return;

	os << "// Fragment outputs\n";
	int colorIndex = 0;
	for (const auto& o : spec.outputs)
	{
		if (o.type == "color")
			os << "layout(location = " << colorIndex++ << ") out vec4 " << o.name << ";\n";
		else if (o.type == "depth")
			os << "layout(depth_any) out float " << o.name << ";\n";
	}
	os << '\n';
}

std::string ShaderGenerator::MainTemplate(Stage stage, MaterialPass pass, Pipeline pipeline) const
{
	if (stage == Stage::Vertex)
	{
		switch (pass)
		{
		case MaterialPass::Depth:    return "surface_depth_main.vs";
		case MaterialPass::Surface:  return (pipeline == Pipeline::FORWARD)
		                            ? "surface_forward_main.vs"
		                            : "surface_deferred_main.vs";
		case MaterialPass::Lighting: return "surface_shading_main.vs";
		}
	}
	else
	{
		switch (pass)
		{
		case MaterialPass::Depth:    return "surface_depth_main.fs";
		case MaterialPass::Surface:  return (pipeline == Pipeline::FORWARD)
		                            ? "surface_forward_main.fs"
		                            : "surface_deferred_main.fs";
		case MaterialPass::Lighting: return "surface_shading_main.fs";
		}
	}
	return {};
}

// =============================================================================
// Constructor
// =============================================================================

ShaderGenerator::ShaderGenerator(MaterialBuilder::PropertyList const& properties,
	MaterialBuilder::VariableList const& variables,
	MaterialBuilder::OutputList const& outputs,
	MaterialBuilder::PreprocessorDefineList const& defines,
	MaterialBuilder::PushConstantList const& pushConstants,
	std::string const& materialCode, size_t lineOffset,
	std::string const& materialVertexCode, size_t vertexLineOffset,
	MaterialBuilder::MaterialDomain materialDomain)
	: m_Defines(defines)
	, m_PushConstants(pushConstants)
	, m_MaterialLineOffset(lineOffset)
	, m_MaterialVertexCode(materialVertexCode)
	, m_MaterialVertexLineOffset(vertexLineOffset)
	, m_MaterialDomain(materialDomain)
{
	std::copy(std::begin(properties), std::end(properties), std::begin(m_Properties));
	std::copy(std::begin(variables), std::end(variables), std::begin(m_Variables));
	std::copy(std::begin(outputs), std::end(outputs), std::back_inserter(m_Outputs));

	m_MaterialFragmentCode = materialCode;
	m_MaterialVertexCode = materialVertexCode;
	m_IsMaterialVertexShaderEmpty = materialVertexCode.empty();

	if (m_MaterialFragmentCode.empty())
	{
		if (m_MaterialDomain == MaterialBuilder::MaterialDomain::SURFACE)
			m_MaterialFragmentCode = "void material(inout MaterialInputs m) {\n    prepareMaterial(m);\n}\n";
		else if (m_MaterialDomain == MaterialBuilder::MaterialDomain::POST_PROCESS)
			m_MaterialFragmentCode = "void postProcess(inout PostProcessInputs p) {\n}\n";
		else if (m_MaterialDomain == MaterialBuilder::MaterialDomain::COMPUTE)
			m_MaterialFragmentCode = "void compute() {\n}\n";
	}

	if (m_MaterialVertexCode.empty())
	{
		if (m_MaterialDomain == MaterialBuilder::MaterialDomain::SURFACE)
			m_MaterialVertexCode = "void materialVertex(inout MaterialVertexInputs m) {\n}\n";
		else if (m_MaterialDomain == MaterialBuilder::MaterialDomain::POST_PROCESS)
			m_MaterialVertexCode = "void postProcessVertex(inout PostProcessVertexInputs m) {\n}\n";
	}
}

// =============================================================================
// Surface-domain dispatch
// =============================================================================

std::string ShaderGenerator::GenerateShader(Stage stage, MaterialPass pass,
                                            const MaterialSpec& spec,
                                            const std::string& userCode) const
{
	switch (stage)
	{
	case Stage::Vertex:
		switch (pass)
		{
		case MaterialPass::Depth:    return GenDepthVS(spec, userCode);
		case MaterialPass::Surface:  return GenSurfaceVS(spec, userCode);
		case MaterialPass::Lighting: return GenLightingVS(spec, userCode);
		}
		break;

	case Stage::Fragment:
		switch (pass)
		{
		case MaterialPass::Depth:    return GenDepthFS(spec, userCode);
		case MaterialPass::Surface:  return GenSurfaceFS(spec, userCode);
		case MaterialPass::Lighting: return GenLightingFS(spec, userCode);
		}
		break;

	case Stage::Compute:
		return GenerateComputeShader(spec, userCode);
	}
	return {};
}

std::string ShaderGenerator::GeneratePostProcessShader(Stage stage,
                                                       const MaterialSpec& spec,
                                                       const std::string& userCode) const
{
	switch (stage)
	{
	case Stage::Vertex:   return GenPostProcessVS(spec, userCode);
	case Stage::Fragment: return GenPostProcessFS(spec, userCode);
	default: return {};
	}
}

// =============================================================================
// Depth — Vertex
// =============================================================================

std::string ShaderGenerator::GenDepthVS(const MaterialSpec& spec, const std::string& code) const
{
	std::ostringstream os;
	CodeGenerator cg;

	EmitHeader(os, cg, spec);
	os << '\n';

	if (m_TargetVulkan)
		os << "#define TARGET_VULKAN_ENVIRONMENT\n";
	os << "#define VERTEX_STAGE\n\n";

	os << LoadTemplate("common_defines.glsl") << '\n';
	os << LoadTemplate("common_math.glsl") << '\n';

	EmitVertexInputs(os, spec);
	EmitVaryingOut(os);

	for (auto& file : Provider::GetDepthVertex())
		os << LoadTemplate(file) << '\n';

	os << LoadTemplate("common_getter.glsl") << '\n';
	cg.generateVaryingDeclarations(os, spec, "out");

	if (!code.empty())
		os << "// User vertex code\n" << code << '\n';

	os << LoadTemplate(MainTemplate(Stage::Vertex, MaterialPass::Depth, spec.pipeline)) << '\n';
	return os.str();
}

