	std::ostringstream os; CodeGenerator cg; EmitHeader(os,cg,spec);
	if(m_TargetVulkan)os<<"#define TARGET_VULKAN_ENVIRONMENT\n";os<<"#define FRAGMENT_STAGE\n\n";
